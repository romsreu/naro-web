export default function AccountSidebar({ nombre }: { nombre: string }) {
  const pathname = usePathname()
  const initial = nombre.charAt(0).toUpperCase()
  const apellidoInitial = nombre.includes(' ') ? nombre.split(' ')[1]?.charAt(0).toUpperCase() : ''

  return (
    <aside className={styles.sidebar}>
      <div className={styles.user}>
        <div className={styles.avatar}>{initial}{apellidoInitial}</div>
        <span className={styles.nombre}>{nombre}</span>
      </div>

      <nav className={styles.nav}>
        {NAV_ITEMS.map(item => {
          const active = item.href ? pathname.startsWith(item.href) : false

          if (item.href) {
            return (
              <Link
                key={item.label}
                href={item.href}
                className={`${styles.navItem} ${active ? styles.active : ''}`}
              >
                {item.icon}
                {item.label}
              </Link>
            )
          }

          return (
            <span key={item.label} className={`${styles.navItem} ${styles.soon}`}>
              {item.icon}
              {item.label}
            </span>
          )
        })}
      </nav>
    </aside>
  )
}
